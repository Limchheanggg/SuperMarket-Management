from app.core.database import SessionLocal
from app.models.product import Product
from app.models.category import Category
from app.models.inventory import Inventory

db = SessionLocal()

def get_or_create_category(name):
    cat = db.query(Category).filter(Category.Category_Name == name).first()
    if not cat:
        cat = Category(Category_Name=name)
        db.add(cat)
        db.commit()
        db.refresh(cat)
    return cat.Category_ID

def add(barcode, name, cat_id, brand, unit, price, perishable=0, stock=50, reorder=10):
    if db.query(Product).filter(Product.Barcode == barcode).first():
        return
    p = Product(Barcode=barcode, Name=name, Category_ID=cat_id, Brand=brand,
                Unit=unit, Unit_Price=price, Is_Perishable=perishable, Reorder_Level=reorder)
    db.add(p)
    db.commit()
    db.refresh(p)
    db.add(Inventory(Product_ID=p.Product_ID, Quantity=stock))
    db.commit()
    print(f"  + {name}")

